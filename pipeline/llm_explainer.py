#!/usr/bin/env python3
"""
llm_explainer.py
================
AI-Assisted Privilege Escalation & Living-off-the-Land (LOLBin) Detection Project
Zero-Shot LLM Attribution & SOC Explainability Layer

Grounding Literature:
  - Ali & Kostakos (2023) [HuntGPT]: Combining ML anomaly detection with LLM explainability
  - Houssel et al. (2024): Explainable intrusion detection using LLMs & hallucination control
  - Ferrag et al. (IEEE Access 2024): Zero-shot reasoning over structured telemetry

Provides:
  1. Live Zero-Shot LLM query interface (OpenAI / Anthropic / Groq / Ollama compatible)
  2. High-fidelity Deterministic Offline Fallback Mode (for reproducible CI / offline benchmarks)
"""

import os
import json
import re
from typing import Dict, Any, Optional

SYSTEM_PROMPT = """You are a Tier-3 Senior Security Operations Center (SOC) Analyst and Threat Hunter.
Your role is to analyze flagged endpoint anomaly payloads generated by an unsupervised machine learning detection engine (Isolation Forest).
You are provided with:
1. The raw command-line and process details.
2. The statistical feature deviations (z-scores relative to the benign baseline).
3. The session context and execution metadata (including sliding window commands).

Provide a grounded, objective assessment. Do NOT hallucinate commands or artifacts not present in the payload.

You MUST respond strictly with a valid JSON object matching this schema:
{
  "verdict": "Malicious - PrivEsc/LOLBin" | "Malicious - Chained PrivEsc/LOLBin Sequence" | "Malicious - Obfuscated LOLBin Aliasing" | "Suspicious" | "False Positive",
  "attributed_technique": "<Specific Technique Name> (e.g. Sudo GTFOBins Abuse, Certutil Ingress Tool Transfer, Chained Discovery & Privilege Escalation Sequence)",
  "mitre_id": "<MITRE ATT&CK ID e.g. T1548.003, T1059 / T1087, T1027.010>",
  "confidence_score": <float between 0.0 and 1.0>,
  "plain_english_explanation": "<Concise 2-3 sentence justification explaining why the feature deviations, command semantics, and sliding window context indicate benign behavior or an attack vector>"
}
"""

class LLMExplainer:
    def __init__(self, provider: Optional[str] = None, api_key: Optional[str] = None, model: Optional[str] = None):
        """
        Initializes the explainer.
        If no API key is set via parameters or environment, defaults to offline deterministic fallback mode.
        """
        self.api_key = api_key or os.getenv("OPENAI_API_KEY") or os.getenv("ANTHROPIC_API_KEY") or os.getenv("GROQ_API_KEY")
        self.provider = provider or ("openai" if os.getenv("OPENAI_API_KEY") else ("anthropic" if os.getenv("ANTHROPIC_API_KEY") else ("groq" if os.getenv("GROQ_API_KEY") else "offline")))
        self.model = model or os.getenv("LLM_MODEL", "gpt-4o-mini" if self.provider == "openai" else "claude-3-haiku-20240307")

        if not self.api_key:
            self.provider = "offline"

    def explain_anomaly(self, anomaly_payload: Dict[str, Any]) -> Dict[str, Any]:
        """
        Generates technique attribution and plain-English SOC explanation.
        Dispatches to live LLM if available, otherwise executes deterministic offline SOC reasoning.
        """
        if self.provider == "offline":
            return self._offline_soc_reasoning(anomaly_payload)

        try:
            return self._call_live_api(anomaly_payload)
        except Exception as e:
            # Fall back to offline reasoning seamlessly if live API call fails
            fallback = self._offline_soc_reasoning(anomaly_payload)
            fallback["plain_english_explanation"] += f" (Note: generated via offline analyst engine due to API condition: {str(e)[:50]})"
            return fallback

    def _call_live_api(self, payload: Dict[str, Any]) -> Dict[str, Any]:
        """Queries live LLM API with structured prompt."""
        import requests

        user_content = (
            f"ANOMALY PAYLOAD TO EVALUATE:\n"
            f"```json\n{json.dumps(payload, indent=2)}\n```\n"
            f"Analyze the command semantics, process lineage, and feature deviations. Output valid JSON only."
        )

        if self.provider == "openai" or self.provider == "groq":
            url = "https://api.openai.com/v1/chat/completions" if self.provider == "openai" else "https://api.groq.com/openai/v1/chat/completions"
            headers = {
                "Authorization": f"Bearer {self.api_key}",
                "Content-Type": "application/json"
            }
            body = {
                "model": self.model,
                "messages": [
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {"role": "user", "content": user_content}
                ],
                "temperature": 0.1,
                "response_format": {"type": "json_object"}
            }
            resp = requests.post(url, headers=headers, json=body, timeout=15)
            resp.raise_for_status()
            res_json = resp.json()
            raw_text = res_json["choices"][0]["message"]["content"]
            return json.loads(raw_text)

        elif self.provider == "anthropic":
            url = "https://api.anthropic.com/v1/messages"
            headers = {
                "x-api-key": self.api_key,
                "anthropic-version": "2023-06-01",
                "Content-Type": "application/json"
            }
            body = {
                "model": self.model,
                "system": SYSTEM_PROMPT,
                "messages": [{"role": "user", "content": user_content}],
                "max_tokens": 1024,
                "temperature": 0.1
            }
            resp = requests.post(url, headers=headers, json=body, timeout=15)
            resp.raise_for_status()
            res_json = resp.json()
            raw_text = res_json["content"][0]["text"]
            # Extract JSON block
            match = re.search(r"\{.*\}", raw_text, re.DOTALL)
            if match:
                return json.loads(match.group(0))
            return json.loads(raw_text)

        else:
            return self._offline_soc_reasoning(payload)

    def _offline_soc_reasoning(self, payload: Dict[str, Any]) -> Dict[str, Any]:
        """
        High-fidelity deterministic SOC reasoning engine.
        Grounded in MITRE ATT&CK, GTFOBins, and LOLBins rules.
        Inspects command-line syntax, sliding window session context, and statistical deviations.
        """
        cmd = (payload.get("command_line") or "").strip()
        cmd_lower = cmd.lower()
        proc = (payload.get("process_name") or "").lower()
        top_devs = {d["feature"]: d["z_score"] for d in payload.get("top_feature_deviations", [])}
        score = float(payload.get("anomaly_score", 0.5))
        window_cmds = payload.get("sliding_window_commands") or []
        window_text = " ".join(window_cmds).lower()

        # 1. Environment-Variable Aliasing & Indirect LOLBin Invocation (MITRE T1027.010)
        # Catches 'set p=certutil&& call %p%', '$env:TEMP', 'IFS=', and dynamic variable aliasing
        is_aliasing = (
            bool(re.search(r"set\s+[a-zA-Z0-9_]+\s*=", cmd_lower)) or
            "call %" in cmd_lower or
            "$env:" in cmd_lower or
            "ifs=" in cmd_lower or
            bool(re.search(r"%[a-zA-Z0-9_]+%", cmd_lower))
        )
        if is_aliasing:
            aliased_target = "LOLBin"
            for b in ["certutil", "powershell", "cmd", "mshta", "rundll32", "regsvr32", "wmic", "bitsadmin", "curl", "find", "sh"]:
                if b in cmd_lower or b in window_text:
                    aliased_target = b
                    break
            return {
                "verdict": "Malicious - Obfuscated LOLBin Aliasing",
                "attributed_technique": f"Obfuscated LOLBin Aliasing via Environment Variables ({aliased_target})",
                "mitre_id": "T1027.010",
                "confidence_score": 0.94,
                "plain_english_explanation": (
                    f"The command utilizes environment-variable aliasing syntax ('{cmd[:55]}...') to dynamically assign "
                    f"and dereference binary paths, evading static string-matching rules while executing {aliased_target}. "
                    f"This technique maps directly to MITRE ATT&CK T1027.010 (Command Obfuscation: Environment Variables)."
                )
            }

        # 2. Chained Multi-Step Sequences & Discovery/Staging (MITRE T1059 / T1087)
        # Evaluates sliding window context (Springer 2026) to detect multi-command post-exploitation chains
        recon_tokens = ["whoami", "id", "hostname", "systeminfo", "net user", "whoami /priv"]
        exploit_tokens = ["sudo", "checkpoint", "curl", "powershell", "certutil", "/etc/shadow", "chmod u+s", "/dev/null"]
        
        has_inline_chaining = ("&&" in cmd_lower or ";" in cmd_lower or "|" in cmd_lower) and any(tok in cmd_lower for tok in recon_tokens)
        has_window_sequence = (
            len(window_cmds) > 1 and
            any(any(rt in c.lower() for rt in recon_tokens) for c in window_cmds) and
            (any(any(et in c.lower() for et in exploit_tokens) for c in window_cmds) or top_devs.get("priv_escalated_in_window", 0) > 0.5)
        )
        has_sequence_dynamics = top_devs.get("token_acceleration", 0) > 1.0 or top_devs.get("priv_escalated_in_window", 0) > 0.5

        is_chained_sequence = has_inline_chaining or has_window_sequence or has_sequence_dynamics
        if is_chained_sequence:
            context_summary = " -> ".join([f"'{c}'" for c in window_cmds[:3]]) if window_cmds else f"'{cmd}' -> [privilege escalation / exfiltration]"
            return {
                "verdict": "Malicious - Chained PrivEsc/LOLBin Sequence",
                "attributed_technique": "Chained Discovery & Privilege Escalation Sequence",
                "mitre_id": "T1059 / T1087",
                "confidence_score": 0.92,
                "plain_english_explanation": (
                    f"While isolated execution of '{cmd}' resembles benign administrative user discovery, "
                    f"inspection of the sliding window context ({context_summary}) reveals it forms the initial "
                    f"reconnaissance phase of an automated multi-step attack chain. The command connects directly to "
                    f"subsequent privilege escalation and staging activities within the session, warranting a critical alert."
                )
            }

        # 3. Base64 Obfuscation & Encoded Payload Staging (MITRE T1059.001 / T1027)
        if (
            "base64" in cmd_lower or
            top_devs.get("has_base64", 0) > 1.0 or
            "-e jab" in cmd_lower or
            "-enc " in cmd_lower or
            "-encodedcommand" in cmd_lower or
            (top_devs.get("entropy", 0) > 1.8 and len(cmd) > 60)
        ):
            return {
                "verdict": "Malicious - PrivEsc/LOLBin",
                "attributed_technique": "Obfuscated / Base64 Encoded Command Execution",
                "mitre_id": "T1059.001 / T1027",
                "confidence_score": 0.96,
                "plain_english_explanation": (
                    f"The command invokes an encoded payload with elevated entropy and base64 parameters. "
                    f"Process '{proc}' deviates significantly from benign baseline with statistical z-score {top_devs.get('entropy', 2.1):.1f} on entropy. "
                    f"This pattern is strongly indicative of payload staging and defense evasion."
                )
            }

        # 2. Linux GTFOBins & Sudo / SUID
        if "sudo" in cmd or "sudoers" in cmd or top_devs.get("sudo_invoked", 0) > 1.0:
            if "find" in proc or "-exec" in cmd:
                return {
                    "verdict": "Malicious - PrivEsc/LOLBin",
                    "attributed_technique": "GTFOBins Sudo Abuse (find -exec)",
                    "mitre_id": "T1548.003",
                    "confidence_score": 0.95,
                    "plain_english_explanation": (
                        "Execution of find with the -exec parameter under elevated privileges matches known GTFOBins "
                        "privilege escalation vectors. Anomaly score of {:.2f} reflects abnormal privilege transition.".format(score)
                    )
                }
            if "vim" in proc or ":!/bin" in cmd:
                return {
                    "verdict": "Malicious - PrivEsc/LOLBin",
                    "attributed_technique": "GTFOBins Sudo Abuse (vim shell escape)",
                    "mitre_id": "T1548.003",
                    "confidence_score": 0.95,
                    "plain_english_explanation": (
                        "Execution of vim with command execution flags (:!/bin/sh) under sudo privileges matches known "
                        "interactive shell escape techniques."
                    )
                }
            if "awk" in proc or "system(" in cmd:
                return {
                    "verdict": "Malicious - PrivEsc/LOLBin",
                    "attributed_technique": "GTFOBins Sudo Abuse (awk system call)",
                    "mitre_id": "T1548.003",
                    "confidence_score": 0.94,
                    "plain_english_explanation": (
                        "Awk invoked with BEGIN {system('/bin/sh')} under sudo. This allows immediate unconfined root shell instantiation."
                    )
                }
            if "tar" in proc or "checkpoint" in cmd:
                return {
                    "verdict": "Malicious - PrivEsc/LOLBin",
                    "attributed_technique": "Tar Wildcard Privilege Escalation",
                    "mitre_id": "T1548.003",
                    "confidence_score": 0.93,
                    "plain_english_explanation": (
                        "Execution of tar with --checkpoint-action=exec parameter. This is a classic wildcard/privilege escalation vector."
                    )
                }
            if "sudoers" in cmd or "nopasswd" in cmd:
                return {
                    "verdict": "Malicious - PrivEsc/LOLBin",
                    "attributed_technique": "Sudoers Configuration File Modification",
                    "mitre_id": "T1548.003",
                    "confidence_score": 0.98,
                    "plain_english_explanation": (
                        "Direct manipulation or append to /etc/sudoers granting NOPASSWD privileges detected. Critical PrivEsc indicator."
                    )
                }
            return {
                "verdict": "Suspicious",
                "attributed_technique": "Privileged Sudo Invocation Anomaly",
                "mitre_id": "T1548.003",
                "confidence_score": 0.85,
                "plain_english_explanation": (
                    f"Command '{cmd[:60]}' invoked sudo with non-baseline lineage and anomalous privilege transition."
                )
            }

        # 3. Windows LOLBins
        if "certutil" in proc or "certutil" in cmd:
            if "urlcache" in cmd or "-split" in cmd:
                return {
                    "verdict": "Malicious - PrivEsc/LOLBin",
                    "attributed_technique": "Certutil Ingress Tool Transfer",
                    "mitre_id": "T1105",
                    "confidence_score": 0.97,
                    "plain_english_explanation": (
                        "Certutil.exe was invoked with '-urlcache -split -f' flags to download remote content. "
                        "This is a classic Living-off-the-Land ingress tool transfer (Barr-Smith et al., 2021)."
                    )
                }
        if "mshta" in proc or "mshta" in cmd:
            return {
                "verdict": "Malicious - PrivEsc/LOLBin",
                "attributed_technique": "Mshta Arbitrary Script Execution",
                "mitre_id": "T1218.005",
                "confidence_score": 0.95,
                "plain_english_explanation": (
                    "Mshta.exe executed inline VBScript/JScript commands, bypassing standard application execution policies."
                )
            }
        if "regsvr32" in proc or "scrobj.dll" in cmd:
            return {
                "verdict": "Malicious - PrivEsc/LOLBin",
                "attributed_technique": "Regsvr32 Squiblydoo Scriptlet Bypass",
                "mitre_id": "T1218.010",
                "confidence_score": 0.96,
                "plain_english_explanation": (
                    "Regsvr32 invoked with remote scriptlet URL (/i flag) and scrobj.dll. This executes unmanaged COM scriptlets in memory."
                )
            }
        if "rundll32" in proc:
            return {
                "verdict": "Malicious - PrivEsc/LOLBin",
                "attributed_technique": "Rundll32 DLL Execution",
                "mitre_id": "T1218.011",
                "confidence_score": 0.90,
                "plain_english_explanation": (
                    "Rundll32 invoked with unusual DLL export path, deviating strongly from baseline system service behaviors."
                )
            }
        if "wmic" in proc and ("call create" in cmd or "process" in cmd):
            return {
                "verdict": "Malicious - PrivEsc/LOLBin",
                "attributed_technique": "WMIC Process Execution",
                "mitre_id": "T1047",
                "confidence_score": 0.91,
                "plain_english_explanation": (
                    "WMIC utilized to spawn external processes, bypassing local process tree restrictions."
                )
            }
        if "bitsadmin" in proc and ("/transfer" in cmd or "/download" in cmd):
            return {
                "verdict": "Malicious - PrivEsc/LOLBin",
                "attributed_technique": "BITSAdmin Ingress Download Job",
                "mitre_id": "T1197",
                "confidence_score": 0.92,
                "plain_english_explanation": (
                    "BITSAdmin job created to fetch external binaries via background intelligent transfer service."
                )
            }
        if "powershell" in proc and ("bypass" in cmd or "webclient" in cmd or "iex" in cmd):
            return {
                "verdict": "Malicious - PrivEsc/LOLBin",
                "attributed_technique": "PowerShell Unrestricted Execution / Staging",
                "mitre_id": "T1059.001",
                "confidence_score": 0.93,
                "plain_english_explanation": (
                    "PowerShell invoked with ExecutionPolicy Bypass and inline download cradle syntax. Strong indicator of initial staging."
                )
            }
        if "sc.exe" in proc or "binpath=" in cmd:
            return {
                "verdict": "Malicious - PrivEsc/LOLBin",
                "attributed_technique": "Service Binary Path Modification",
                "mitre_id": "T1543.003",
                "confidence_score": 0.94,
                "plain_english_explanation": (
                    "Windows Service Manager (sc.exe) reconfiguring service binary path (binPath) to execute arbitrary payload."
                )
            }
        if "sam" in cmd or "sekurlsa" in cmd or "lsass" in cmd:
            return {
                "verdict": "Malicious - PrivEsc/LOLBin",
                "attributed_technique": "Credential Access / SAM Registry Exfiltration",
                "mitre_id": "T1003",
                "confidence_score": 0.96,
                "plain_english_explanation": (
                    "Command targets local credential store (SAM/SYSTEM hive or LSASS memory) for offline cracking or token manipulation."
                )
            }

        # 4. Fallback: Check if benign or generic anomaly
        if score < 0.4:
            return {
                "verdict": "False Positive",
                "attributed_technique": "Benign Administrative Command Deviation",
                "mitre_id": "None",
                "confidence_score": 0.82,
                "plain_english_explanation": (
                    f"Process '{proc}' exhibited minor feature deviations ({list(top_devs.keys())[:2]}), but command line "
                    f"semantics represent legitimate administrative utility usage without exploit mechanics."
                )
            }

        return {
            "verdict": "Suspicious",
            "attributed_technique": "Unclassified Behavioral Anomaly",
            "mitre_id": "T1059",
            "confidence_score": 0.75,
            "plain_english_explanation": (
                f"Statistical anomaly score {score:.2f} flagged significant deviations in "
                f"{', '.join(list(top_devs.keys())[:3])}. Semantics warrant SOC analyst review."
            )
        }
