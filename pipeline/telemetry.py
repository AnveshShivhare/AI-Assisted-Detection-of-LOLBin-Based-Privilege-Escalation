#!/usr/bin/env python3
"""
telemetry.py
============
AI-Assisted Privilege Escalation & Living-off-the-Land (LOLBin) Detection Project
Telemetry Ingestion & Normalization Layer

Provides an abstract TelemetrySource adapter and three concrete implementations:
  1. SyntheticTelemetrySource: Ingests synthetic JSON datasets generated by generate_synthetic_telemetry.py
  2. AuditdTelemetrySource: Ingests and parses real Linux auditd logs into the normalized schema.
  3. SysmonTelemetrySource: Ingests and parses Windows Sysmon JSON logs (EventID 1 & 11) into the normalized schema.

Every record emitted contains the metadata field `source_provenance` ("synthetic" vs. "real_auditd")
to guarantee scientific traceability.
"""

import os
import re
import json
import uuid
from abc import ABC, abstractmethod
from datetime import datetime, timezone
from typing import Iterator, Dict, Any, List, Optional


class TelemetrySource(ABC):
    """Abstract Base Class for endpoint telemetry ingestion adapters."""

    @abstractmethod
    def events(self) -> Iterator[Dict[str, Any]]:
        """Yields normalized telemetry event dictionaries."""
        pass

    @property
    @abstractmethod
    def provenance(self) -> str:
        """Returns provenance identifier ('synthetic' or 'real_auditd')."""
        pass


class SyntheticTelemetrySource(TelemetrySource):
    """
    Ingests pre-generated synthetic Sysmon / auditd JSON telemetry files.
    Clearly marks all records with source_provenance='synthetic'.
    """

    def __init__(self, file_path_or_data: Any, label_override: Optional[str] = None):
        self.file_path_or_data = file_path_or_data
        self.label_override = label_override

    @property
    def provenance(self) -> str:
        return "synthetic"

    def events(self) -> Iterator[Dict[str, Any]]:
        if isinstance(self.file_path_or_data, str):
            with open(self.file_path_or_data, "r", encoding="utf-8") as f:
                raw_events = json.load(f)
        elif isinstance(self.file_path_or_data, list):
            raw_events = self.file_path_or_data
        else:
            raise ValueError(f"Unsupported data input: {type(self.file_path_or_data)}")

        for ev in raw_events:
            normalized = dict(ev)
            normalized["source_provenance"] = self.provenance
            if "syscall" not in normalized:
                normalized["syscall"] = "execve"
            if "success" not in normalized:
                normalized["success"] = "yes"
            if "key" not in normalized:
                normalized["key"] = ""
            if "cwd" not in normalized:
                normalized["cwd"] = ""
            if self.label_override:
                normalized["label"] = self.label_override
            yield normalized


class AuditdTelemetrySource(TelemetrySource):
    """
    Parses real raw Linux auditd output (e.g. from ausearch -k exec -i or /var/log/audit/audit.log).
    Groups log entries by audit message ID (msg=audit(epoch:ID)), correlates
    SYSCALL, EXECVE, PATH, CWD, and PROCTITLE records, and reconstructs the full
    normalized telemetry schema.
    """

    def __init__(self, log_path_or_text: str, host: str = "srv-linux-live", is_file: bool = True, assume_benign: bool = False):
        self.log_path_or_text = log_path_or_text
        self.host = host
        self.is_file = is_file
        self.assume_benign = assume_benign

    @property
    def provenance(self) -> str:
        if self.assume_benign:
            return "real_auditd (known-benign baseline assumption)"
        return "real_auditd"

    def _parse_timestamp(self, ts_str: str) -> str:
        """
        Parses auditd timestamp which can appear as:
          - epoch.msec: e.g. "1761234567.123"
          - date time.msec: e.g. "10/23/2026 21:12:31.068"
        Returns standard ISO-8601 string in UTC.
        """
        ts_str = ts_str.strip()
        try:
            # Check epoch float format
            epoch_val = float(ts_str)
            dt = datetime.fromtimestamp(epoch_val, tz=timezone.utc)
            return dt.isoformat()
        except ValueError:
            pass

        # Check MM/DD/YYYY HH:MM:SS.mmm format
        for fmt in ("%m/%d/%Y %H:%M:%S.%f", "%m/%d/%Y %H:%M:%S", "%Y-%m-%d %H:%M:%S.%f", "%Y-%m-%d %H:%M:%S"):
            try:
                dt = datetime.strptime(ts_str, fmt).replace(tzinfo=timezone.utc)
                return dt.isoformat()
            except ValueError:
                continue

        return datetime.now(timezone.utc).isoformat()

    def _parse_key_value_pairs(self, line: str) -> Dict[str, str]:
        """Extracts key=value tokens from an auditd line, respecting quotes."""
        kvs = {}
        # Regex captures: key="quoted value" or key=unquoted_value
        pattern = re.compile(r'([a-zA-Z0-9_]+)=(?:"([^"]*)"|([^\s]+))')
        for match in pattern.finditer(line):
            k = match.group(1)
            v = match.group(2) if match.group(2) is not None else match.group(3)
            kvs[k] = v
        return kvs

    def _resolve_id(self, val_str: Optional[str], default: int = 1000) -> int:
        """Converts user/group ID to int, handling 'root' or names safely."""
        if val_str is None:
            return default
        val_str = str(val_str).strip()
        if val_str == "root":
            return 0
        try:
            return int(val_str)
        except ValueError:
            return default

    def events(self) -> Iterator[Dict[str, Any]]:
        """Yields grouped and normalized events from auditd log entries."""
        lines = []
        if self.is_file and os.path.exists(self.log_path_or_text):
            with open(self.log_path_or_text, "r", encoding="utf-8", errors="replace") as f:
                lines = f.readlines()
        else:
            lines = self.log_path_or_text.splitlines()

        # Group records by msg=audit(...:ID)
        # Matches: msg=audit(TIMESTAMP:ID)
        msg_regex = re.compile(r"msg=audit\((.+):(\d+)\)")

        groups: Dict[str, List[Dict[str, Any]]] = {}
        raw_logs: Dict[str, List[str]] = {}

        for line in lines:
            line_str = line.strip()
            if not line_str:
                continue

            # Extract record type
            type_match = re.search(r"type=([A-Z_]+)", line_str)
            rec_type = type_match.group(1) if type_match else "UNKNOWN"

            # Extract msg=audit(...)
            m_match = msg_regex.search(line_str)
            if not m_match:
                continue

            ts_raw = m_match.group(1)
            event_id = m_match.group(2)

            if event_id not in groups:
                groups[event_id] = []
                raw_logs[event_id] = []

            kvs = self._parse_key_value_pairs(line_str)
            kvs["_type"] = rec_type
            kvs["_timestamp_raw"] = ts_raw
            groups[event_id].append(kvs)
            raw_logs[event_id].append(line_str)

        # Assemble normalized events
        for msg_id, rec_list in groups.items():
            syscall_rec = next((r for r in rec_list if r["_type"] == "SYSCALL"), None)
            execve_rec = next((r for r in rec_list if r["_type"] == "EXECVE"), None)
            proctitle_rec = next((r for r in rec_list if r["_type"] == "PROCTITLE"), None)
            cwd_rec = next((r for r in rec_list if r["_type"] == "CWD"), None)
            path_recs = [r for r in rec_list if r["_type"] == "PATH"]

            if not syscall_rec and not execve_rec:
                # Need at least SYSCALL or EXECVE for a process event
                continue

            primary = syscall_rec if syscall_rec else execve_rec
            ts_iso = self._parse_timestamp(primary.get("_timestamp_raw", ""))

            # Process attributes
            pid = self._resolve_id(primary.get("pid"), default=1000)
            ppid = self._resolve_id(primary.get("ppid"), default=1)
            uid = self._resolve_id(primary.get("uid"), default=1000)
            euid = self._resolve_id(primary.get("euid"), default=uid)
            gid = self._resolve_id(primary.get("gid"), default=uid)
            user = primary.get("auid") or primary.get("uid") or ("root" if uid == 0 else "ubuntu")
            comm = primary.get("comm", "")
            exe = primary.get("exe", "")

            # Reconstruct command line from EXECVE a0, a1, a2, ...
            cmd_args = []
            if execve_rec:
                # Find all a0, a1, a2... in key order
                arg_keys = [k for k in execve_rec.keys() if re.match(r"^a\d+$", k)]
                arg_keys.sort(key=lambda k: int(k[1:]))
                cmd_args = [execve_rec[k] for k in arg_keys if execve_rec[k] is not None]

            if cmd_args:
                command_line = " ".join(cmd_args)
            elif proctitle_rec and "proctitle" in proctitle_rec:
                raw_pt = proctitle_rec["proctitle"]
                if re.match(r"^[0-9a-fA-F]+$", raw_pt) and len(raw_pt) % 2 == 0:
                    try:
                        decoded = bytes.fromhex(raw_pt).decode("utf-8", errors="replace")
                        command_line = decoded.replace("\x00", " ").strip()
                    except Exception:
                        command_line = raw_pt
                else:
                    command_line = raw_pt
            elif exe:
                command_line = exe
            else:
                command_line = comm

            if not comm and exe:
                comm = os.path.basename(exe)

            # File touches from PATH records
            file_touches = []
            for pr in path_recs:
                p_name = pr.get("name")
                if p_name and p_name not in file_touches:
                    file_touches.append(p_name)

            cwd = cwd_rec.get("cwd", "") if cwd_rec else ""
            session_num = primary.get("ses", "1")
            session_id = f"audit_ses_{session_num}"

            # Explicit rule: if session is known-benign, set label="benign" explicitly rather than "unknown"
            label = "benign" if self.assume_benign else "unknown"
            technique = "Benign Baseline Activity" if self.assume_benign else "Real Ingested Telemetry"

            # Assemble normalized event dictionary
            normalized = {
                "event_id": str(uuid.uuid4()),
                "audit_msg_id": msg_id,
                "timestamp": ts_iso,
                "source": "auditd",
                "source_provenance": self.provenance,
                "os_type": "linux",
                "host": self.host,
                "session_id": session_id,
                "process_name": comm,
                "process_path": exe,
                "process_id": pid,
                "parent_process_name": "unknown",
                "parent_process_path": "",
                "parent_process_id": ppid,
                "command_line": command_line,
                "cwd": cwd,
                "syscall": primary.get("syscall", "execve"),
                "success": primary.get("success", "yes"),
                "key": primary.get("key", ""),
                "user": str(user),
                "uid": uid,
                "gid": gid,
                "euid": euid,
                "integrity_level": "None",
                "file_touches": file_touches,
                "label": label,
                "tier": 0,
                "technique": technique,
                "mitre_technique_id": "None",
                "raw_event": "\n".join(raw_logs.get(msg_id, []))
            }
            yield normalized


class SysmonTelemetrySource(TelemetrySource):
    """
    Parses Windows Sysmon JSON logs (specifically EventID 1: Process Creation and EventID 11: File Creation).
    Handles:
      - JSON list of objects: [ {...}, {...} ]
      - Newline-delimited JSON (NDJSON / JSON lines): {...}\n{...}
      - Single JSON object or raw Python dict/list
      - Flat Sysmon fields (Image, CommandLine, User, etc.) or nested EventData / System objects.
    Normalizes Windows telemetry fields into the unified 21-key schema so the feature extractor
    requires zero modifications.
    """

    def __init__(self, log_path_or_data: Any, host: str = "WIN-EDR-LAB01", is_file: bool = True, assume_benign: bool = False, label_override: Optional[str] = None):
        self.log_path_or_data = log_path_or_data
        self.host = host
        self.is_file = is_file
        self.assume_benign = assume_benign
        self.label_override = label_override

    @property
    def provenance(self) -> str:
        if self.assume_benign:
            return "real_sysmon (known-benign baseline assumption)"
        return "real_sysmon"

    def _parse_timestamp(self, ts_str: Optional[str]) -> str:
        """Parses Sysmon UtcTime / TimeCreated into standard UTC ISO-8601 string."""
        if not ts_str:
            return datetime.now(timezone.utc).isoformat()
        ts_str = str(ts_str).strip()
        for fmt in (
            "%Y-%m-%d %H:%M:%S.%f",
            "%Y-%m-%d %H:%M:%S",
            "%Y-%m-%dT%H:%M:%S.%fZ",
            "%Y-%m-%dT%H:%M:%SZ",
            "%Y-%m-%dT%H:%M:%S%z",
            "%Y-%m-%d %H:%M:%S%z"
        ):
            try:
                dt = datetime.strptime(ts_str, fmt)
                if dt.tzinfo is None:
                    dt = dt.replace(tzinfo=timezone.utc)
                return dt.astimezone(timezone.utc).isoformat()
            except ValueError:
                continue

        try:
            dt = datetime.fromisoformat(ts_str.replace("Z", "+00:00"))
            return dt.astimezone(timezone.utc).isoformat()
        except Exception:
            return datetime.now(timezone.utc).isoformat()

    def _resolve_int(self, val: Any, default: int = 1000) -> int:
        """Safely parses integer PID / UID."""
        if val is None:
            return default
        try:
            return int(str(val).strip())
        except (ValueError, TypeError):
            return default

    def _flatten_sysmon_record(self, raw_rec: Dict[str, Any]) -> Dict[str, Any]:
        """Flattens nested System/EventData structures into a unified dictionary."""
        flat = dict(raw_rec)

        # Handle nested Event root: {"Event": {...}}
        if "Event" in flat and isinstance(flat["Event"], dict):
            inner = flat.pop("Event")
            flat.update(inner)

        # Handle System block: {"System": {"EventID": 1, "Computer": ...}}
        if "System" in flat and isinstance(flat["System"], dict):
            sys_block = flat["System"]
            if "EventID" in sys_block:
                eid_val = sys_block["EventID"]
                flat["EventID"] = eid_val.get("#text") if isinstance(eid_val, dict) else eid_val
            if "Computer" in sys_block:
                flat["Computer"] = sys_block["Computer"]
            if "TimeCreated" in sys_block:
                tc = sys_block["TimeCreated"]
                flat["UtcTime"] = tc.get("@SystemTime") if isinstance(tc, dict) else tc

        # Handle EventData block: {"EventData": {"Data": [...]}} or {"EventData": {"Image": ...}}
        if "EventData" in flat:
            ed = flat["EventData"]
            if isinstance(ed, dict):
                if "Data" in ed and isinstance(ed["Data"], list):
                    for item in ed["Data"]:
                        if isinstance(item, dict) and "@Name" in item:
                            flat[item["@Name"]] = item.get("#text", "")
                else:
                    flat.update(ed)
            elif isinstance(ed, list):
                for item in ed:
                    if isinstance(item, dict) and "@Name" in item:
                        flat[item["@Name"]] = item.get("#text", "")

        return flat

    def events(self) -> Iterator[Dict[str, Any]]:
        """Yields grouped and normalized events from Sysmon JSON records."""
        raw_items: List[Dict[str, Any]] = []

        if isinstance(self.log_path_or_data, list):
            raw_items = self.log_path_or_data
        elif isinstance(self.log_path_or_data, dict):
            raw_items = [self.log_path_or_data]
        elif isinstance(self.log_path_or_data, str):
            if self.is_file and os.path.exists(self.log_path_or_data):
                with open(self.log_path_or_data, "r", encoding="utf-8", errors="replace") as f:
                    content = f.read().strip()
                if content.startswith("[") and content.endswith("]"):
                    try:
                        raw_items = json.loads(content)
                    except Exception:
                        raw_items = []
                else:
                    for line in content.splitlines():
                        line_str = line.strip()
                        if not line_str:
                            continue
                        try:
                            raw_items.append(json.loads(line_str))
                        except Exception:
                            continue
            else:
                s = self.log_path_or_data.strip()
                if s.startswith("[") and s.endswith("]"):
                    try:
                        raw_items = json.loads(s)
                    except Exception:
                        raw_items = []
                else:
                    for line in s.splitlines():
                        line_str = line.strip()
                        if not line_str:
                            continue
                        try:
                            raw_items.append(json.loads(line_str))
                        except Exception:
                            continue

        for raw_rec in raw_items:
            flat = self._flatten_sysmon_record(raw_rec)

            event_id_raw = flat.get("EventID") or flat.get("event_id") or flat.get("Id") or 1
            try:
                event_id_int = int(str(event_id_raw).strip())
            except (ValueError, TypeError):
                event_id_int = 1

            # Specifically process EventID 1 (Process Create) and EventID 11 (File Create)
            if event_id_int not in (1, 11):
                continue

            ts_raw = flat.get("UtcTime") or flat.get("TimeCreated") or flat.get("timestamp") or ""
            ts_iso = self._parse_timestamp(ts_raw)

            host = flat.get("Computer") or flat.get("host") or self.host
            user = flat.get("User") or flat.get("user") or "CORP\\User"
            user_str = str(user)
            user_upper = user_str.upper()

            integrity = flat.get("IntegrityLevel") or flat.get("integrity_level") or "Medium"
            is_admin_or_system = ("SYSTEM" in user_upper or "ADMINISTRATOR" in user_upper or integrity in ("High", "System"))
            uid = 0 if is_admin_or_system else 1000
            gid = 0 if is_admin_or_system else 1000
            euid = 0 if is_admin_or_system else 1000

            pid = self._resolve_int(flat.get("ProcessId") or flat.get("process_id"), default=1000)

            label = self.label_override or ("benign" if self.assume_benign else flat.get("label", "unknown"))
            tier = int(flat.get("tier", 0))

            if event_id_int == 1:
                # EventID 1: Process Creation
                image = flat.get("Image") or flat.get("process_path") or flat.get("exe") or ""
                cmdline = flat.get("CommandLine") or flat.get("command_line") or image
                parent_image = flat.get("ParentImage") or flat.get("parent_process_path") or ""
                ppid = self._resolve_int(flat.get("ParentProcessId") or flat.get("parent_process_id"), default=1)
                cwd = flat.get("CurrentDirectory") or flat.get("cwd") or ""

                proc_name = os.path.basename(image.replace("\\", "/")) if image else (flat.get("process_name") or "unknown.exe")
                parent_proc_name = os.path.basename(parent_image.replace("\\", "/")) if parent_image else (flat.get("parent_process_name") or "unknown.exe")

                file_touches = flat.get("file_touches") or []
                if not file_touches and ("\\" in cmdline or "/" in cmdline):
                    tokens = cmdline.split()
                    for tok in tokens[1:]:
                        if ("\\" in tok or "/" in tok) and not tok.startswith("-") and not tok.startswith("/"):
                            file_touches.append(tok.strip("\"'"))

                technique = flat.get("technique") or ("Benign Windows Baseline Activity" if self.assume_benign else "Sysmon Process Creation")
                mitre_id = flat.get("mitre_technique_id") or flat.get("mitre_id") or "None"
                sess_id = flat.get("session_id") or f"win_ses_{user_str.replace('\\', '_')}"

                normalized = {
                    "event_id": str(flat.get("ProcessGuid") or uuid.uuid4()),
                    "sysmon_event_id": 1,
                    "timestamp": ts_iso,
                    "source": "sysmon",
                    "source_provenance": self.provenance,
                    "os_type": "windows",
                    "host": host,
                    "session_id": sess_id,
                    "process_name": proc_name,
                    "process_path": image,
                    "process_id": pid,
                    "parent_process_name": parent_proc_name,
                    "parent_process_path": parent_image,
                    "parent_process_id": ppid,
                    "command_line": cmdline,
                    "cwd": cwd,
                    "syscall": "ProcessCreate",
                    "success": "yes",
                    "key": "process_creation",
                    "user": user_str,
                    "uid": uid,
                    "gid": gid,
                    "euid": euid,
                    "integrity_level": integrity,
                    "file_touches": file_touches,
                    "label": label,
                    "tier": tier,
                    "technique": technique,
                    "mitre_technique_id": mitre_id,
                    "raw_event": json.dumps(raw_rec) if isinstance(raw_rec, dict) else str(raw_rec)
                }
                yield normalized

            elif event_id_int == 11:
                # EventID 11: File Creation
                image = flat.get("Image") or flat.get("process_path") or ""
                target_file = flat.get("TargetFilename") or flat.get("target_filename") or ""
                proc_name = os.path.basename(image.replace("\\", "/")) if image else "unknown.exe"
                cmdline = flat.get("CommandLine") or f"{proc_name} -> {target_file}"
                file_touches = [target_file] if target_file else []

                technique = flat.get("technique") or "Sysmon File Creation"
                mitre_id = flat.get("mitre_technique_id") or flat.get("mitre_id") or "T1105"
                sess_id = flat.get("session_id") or f"win_ses_{user_str.replace('\\', '_')}"

                normalized = {
                    "event_id": str(flat.get("ProcessGuid") or uuid.uuid4()),
                    "sysmon_event_id": 11,
                    "timestamp": ts_iso,
                    "source": "sysmon",
                    "source_provenance": self.provenance,
                    "os_type": "windows",
                    "host": host,
                    "session_id": sess_id,
                    "process_name": proc_name,
                    "process_path": image,
                    "process_id": pid,
                    "parent_process_name": "unknown.exe",
                    "parent_process_path": "",
                    "parent_process_id": 1,
                    "command_line": cmdline,
                    "cwd": "",
                    "syscall": "FileCreate",
                    "success": "yes",
                    "key": "file_creation",
                    "user": user_str,
                    "uid": uid,
                    "gid": gid,
                    "euid": euid,
                    "integrity_level": integrity,
                    "file_touches": file_touches,
                    "label": label,
                    "tier": tier,
                    "technique": technique,
                    "mitre_technique_id": mitre_id,
                    "raw_event": json.dumps(raw_rec) if isinstance(raw_rec, dict) else str(raw_rec)
                }
                yield normalized
